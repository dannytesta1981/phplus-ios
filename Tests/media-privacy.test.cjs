const fs = require('node:fs');
const assert = require('node:assert/strict');
const app = fs.readFileSync('PrivateHub/PrivateHubApp.swift','utf8');
const media = fs.readFileSync('PrivateHub/MediaPrivacy.swift','utf8');
assert(!app.includes('setAllMediaPlaybackSuspended('), 'No persistent media suspension may trap a Face Scan preview');
assert(!app.includes('MediaPrivacyScript'), 'No hidden/pagehide script may pause a permission/verification flow');
assert(!app.includes('isAgeProvider'), 'Provider host must not classify Face Scan as AgeKey');
assert(!app.includes('cancellingVerification'), 'No sticky cancellation flag may veto redirects, dialogs or popups');
assert(!media.includes('visibilitychange'));
assert(!media.includes('pagehide'));
assert(app.includes('decisionHandler(.prompt)'));
assert(!app.includes('decisionHandler(.grant)'));
const response = app.split('decidePolicyFor navigationResponse:')[1].split('createWebViewWith configuration:')[0];
assert(!response.includes('decisionHandler(.cancel)'));
assert(app.includes('WKWebsiteDataStore') || app.includes('configuration.websiteDataStore = .default()'));
console.log('Face Scan regression boundaries: no AgeKey interception, no persistent playback veto, no visibility media hook, per-origin prompt retained: PASS. No physical capture test.');
